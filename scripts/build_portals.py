"""Build career-ops/portals.yml from career-ops' template plus config/portals.fde.yml.

FDE title filter, the template's companies plus our FDE companies (deduped by name or API),
and the template's web search queries disabled so scans stay focused.
Run from the repo root: uv run scripts/build_portals.py
"""
import yaml

t = yaml.safe_load(open("career-ops/templates/portals.example.yml"))
f = yaml.safe_load(open("config/portals.fde.yml"))
names = {c["name"].lower() for c in t["tracked_companies"]}
apis = {str(c.get("api", "")).lower().split("?")[0] for c in t["tracked_companies"]}
added = [c for c in f["tracked_companies"]
         if c["name"].lower() not in names and str(c.get("api") or "~").lower().split("?")[0] not in apis]
for q in t["search_queries"]:
    q["enabled"] = False
ov = f.get("overrides") or {}
for c in t["tracked_companies"] + added:
    o = ov.get(c.get("name"))
    if not o:
        continue
    if "careers_url" in o:
        # Drop any stale provider/api so career-ops re-detects from the new URL.
        for k in ("api", "provider", "scan_method", "scan_query"):
            c.pop(k, None)
    c.update(o)
missing = [n for n in ov if not any(c.get("name") == n for c in t["tracked_companies"] + added)]
if missing:
    print("warning: overrides name no tracked company:", missing)

out = {
    "title_filter": {
        "positive": f["title_filter"]["positive"],
        "negative": list(dict.fromkeys(t["title_filter"].get("negative", []) + f["title_filter"]["negative"])),
        "seniority_boost": t["title_filter"].get("seniority_boost", []),
    },
    "search_queries": f["search_queries"] + t["search_queries"],
    "tracked_companies": t["tracked_companies"] + added,
    "job_boards": t["job_boards"] + f.get("job_boards", []),
}
if "location_filter" in f:
    out["location_filter"] = f["location_filter"]
header = ("# Generated by scripts/build_portals.py. Edit config/portals.fde.yml and re-run, not this file.\n"
          "# All options are documented in templates/portals.example.yml.\n")
open("career-ops/portals.yml", "w").write(header + yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=200))
print(f"added {len(added)} companies; total {len(out['tracked_companies'])}")
